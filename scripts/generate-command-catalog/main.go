// Command generate-command-catalog extracts reserved input from production Go
// handlers. Run from the repository root after adding bot commands.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

func literal(e ast.Expr) string {
	b, ok := e.(*ast.BasicLit)
	if !ok || b.Kind != token.STRING {
		return ""
	}
	s, _ := strconv.Unquote(b.Value)
	if len([]rune(s)) > 60 || strings.ContainsAny(s, "\n\r\t") || s == "" || s == strings.ToUpper(s) && strings.Contains(s, "_") {
		return ""
	}
	for _, r := range s {
		if unicode.Is(unicode.Han, r) {
			return s
		}
	}
	if strings.HasPrefix(s, "/") {
		return s
	}
	return ""
}
func main() {
	exact, prefix, contains := map[string]bool{}, map[string]bool{}, map[string]bool{}
	err := filepath.WalkDir("internal", func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") || strings.Contains(path, "commands_generated") || strings.Contains(path, "lottery_keyword.go") {
			return nil
		}
		f, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
		if err != nil {
			return err
		}
		ast.Inspect(f, func(n ast.Node) bool {
			switch v := n.(type) {
			case *ast.CaseClause:
				for _, e := range v.List {
					if s := literal(e); s != "" {
						exact[s] = true
					}
				}
			case *ast.BinaryExpr:
				if v.Op == token.EQL {
					for _, e := range []ast.Expr{v.X, v.Y} {
						if s := literal(e); s != "" {
							exact[s] = true
						}
					}
				}
			case *ast.CallExpr:
				sel, ok := v.Fun.(*ast.SelectorExpr)
				if !ok {
					break
				}
				if sel.Sel.Name == "NewKeyboardButton" && len(v.Args) > 0 {
					if s := literal(v.Args[0]); s != "" {
						exact[s] = true
					}
				}
				if len(v.Args) != 2 {
					break
				}
				id, ok := v.Args[0].(*ast.Ident)
				if !ok || !(id.Name == "text" || id.Name == "trimmed" || id.Name == "command") {
					break
				}
				if s := literal(v.Args[1]); s != "" {
					if sel.Sel.Name == "HasPrefix" {
						prefix[s] = true
					}
					if sel.Sel.Name == "Contains" {
						contains[s] = true
					}
				}
			case *ast.AssignStmt:
				for _, lhs := range v.Lhs {
					if name, ok := lhs.(*ast.Ident); ok && name.Name == "menuKeywords" {
						for _, rhs := range v.Rhs {
							ast.Inspect(rhs, func(n ast.Node) bool {
								if e, ok := n.(ast.Expr); ok {
									if s := literal(e); s != "" {
										contains[s] = true
									}
								}
								return true
							})
						}
					}
				}
			case *ast.ValueSpec:
				for _, name := range v.Names {
					if strings.HasSuffix(name.Name, "Command") {
						for _, value := range v.Values {
							if s := literal(value); s != "" {
								exact[s] = true
							}
						}
					}
					if name.Name == "menuKeywords" {
						ast.Inspect(v, func(n ast.Node) bool {
							if e, ok := n.(ast.Expr); ok {
								if s := literal(e); s != "" {
									contains[s] = true
								}
							}
							return true
						})
					}
				}
			case *ast.FuncDecl:
				if v.Name.Name == "menuCommandText" || v.Name.Name == "adminMenuCommandText" {
					ast.Inspect(v.Body, func(n ast.Node) bool {
						if r, ok := n.(*ast.ReturnStmt); ok && len(r.Results) > 0 {
							if s := literal(r.Results[0]); s != "" {
								exact[s] = true
							}
						}
						return true
					})
				}
			}
			return true
		})
		return nil
	})
	if err != nil {
		panic(err)
	}
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by go run ./scripts/generate-command-catalog; DO NOT EDIT.\npackage textfmt\n\nimport \"strings\"")
	for _, item := range []struct {
		name   string
		values map[string]bool
	}{{"BotCommandNames", exact}, {"botCommandPrefixes", prefix}, {"botCommandContains", contains}} {
		keys := []string{}
		for s := range item.values {
			keys = append(keys, s)
		}
		sort.Strings(keys)
		fmt.Fprintf(&b, "\nvar %s = []string{\n", item.name)
		for _, s := range keys {
			fmt.Fprintf(&b, "%q,\n", s)
		}
		fmt.Fprintln(&b, "}")
	}
	fmt.Fprintln(&b, `
// IsReservedBotInput mirrors the exact, prefix and menu-substring routing rules.
func IsReservedBotInput(text string) bool {
 if strings.HasPrefix(text, "/") { return true }
 for _, s := range BotCommandNames { if text == s || strings.HasPrefix(text, s+" ") { return true } }
 for _, s := range botCommandPrefixes { if strings.HasPrefix(text,s) { return true } }
 for _, s := range botCommandContains { if strings.Contains(text,s) { return true } }
 return false
}`)
	data, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err = os.WriteFile("internal/textfmt/commands_generated.go", data, 0644); err != nil {
		panic(err)
	}
}
